import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium, webkit } from 'playwright';
import init, { HwpDocument } from '../vendor/rhwp-studio/assets/rhwp-core.js';
const base = process.env.EXAM_SEARCH_URL || 'http://127.0.0.1:8813/';
const evidence = new URL('../_work/compact-toolbar/', import.meta.url);
await mkdir(evidence, {recursive:true});
await init({module_or_path:await readFile(new URL('../vendor/rhwp-studio/assets/rhwp_bg-PUGAA2uC.wasm',import.meta.url))});
const observations=[];
for(const [engine,type] of [['webkit',webkit],['chromium',chromium]]) {
 const browser=await type.launch({headless:true});
 try {
  const page=await browser.newPage({viewport:{width:375,height:900},acceptDownloads:true});
  page.setDefaultTimeout(30000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'?utm_source=qa');
  await page.locator('.landing-subject').first().waitFor();
  await page.goto(base+'?group=science&subject=b1&year=2027&month=6');
  await page.waitForFunction(()=>document.querySelector('#result-list').getAttribute('aria-busy')==='false');
  await page.locator('.card-selection input').first().check();
  await page.locator('#selection-open').click();
  await page.locator('#editable-start').waitFor();
  await page.locator('#editable-start').click();
  await page.waitForFunction(()=>!document.querySelector('#editable-download').disabled,null,{timeout:120000});
  await page.locator('#editable-more > summary').click();
  await page.locator('#editable-view-settings > summary').click();
  assert(await page.locator('#editable-zoom').isVisible());
  await page.locator('#editable-zoom').fill('100');
  await page.locator('#editable-zoom').dispatchEvent('change');
  await page.locator('#editable-format-toggle').click();
  const frame=page.frameLocator('#editable-host iframe');
  await frame.locator('#studio-header').waitFor();
  await page.locator('#editable-more > summary').click();
  await page.locator('#editable-format-toggle').click();
  assert(await frame.locator('#studio-header').isHidden());
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#editable-download').click();
  const download=await downloadPromise;
  const path=new URL(`${engine}-biology.hwpx`,evidence).pathname;
  await download.saveAs(path);
  const doc=new HwpDocument(await readFile(path));
  const text=Array.from({length:doc.getParagraphCount(0)},(_,n)=>doc.getTextRange(0,n,0,2000)).join('\n');
  doc.free();assert.match(text,/작은말조개/);
  await page.screenshot({path:new URL(`${engine}-converted.png`,evidence).pathname});
  await page.locator('#editable-close').click();
  for(const width of [320,820,1440,375]) {
   await page.setViewportSize({width,height:900});
   await page.waitForTimeout(150);
   assert.equal(await page.locator('#selection-open').count(),1);
   assert(await page.locator('#selection-open').isVisible());
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  }
  await page.locator('.card-preview').first().click();
  await page.locator('#detail-content').waitFor();
  assert.equal(Math.round((await page.locator('.detail-header').boundingBox()).height),44);
  await page.locator('.detail-more > summary').click();
  assert(await page.locator('#open-viewer').isVisible());
  await page.locator('#detail-home').click();
  await page.locator('.landing-subject').first().waitFor();
  await page.goto(base+'?group=science&subject=p1&year=2027&mode=files&view=split&file=p1_2027_06.pdf');
  await page.locator('#workspace-convert > summary').click();
  await page.waitForFunction(()=>!document.querySelector('#file-preview-editable').disabled,null,{timeout:90000});
  assert(await page.locator('#file-preview-editable').isVisible());
  await page.locator('#file-preview-editable').click();
  await page.locator('#editable-start').waitFor();
  await page.locator('#editable-close').click();
  await page.goto(base+'?group=science&subject=p1&year=2027&id=p1_2027_06_06');
  await page.locator('#open-editable').click();
  await page.locator('#editable-start').click();
  await page.waitForFunction(()=>!document.querySelector('#editable-download').disabled,null,{timeout:120000});
  await page.frameLocator('#editable-host iframe').getByRole('textbox',{name:'문서 편집 입력'}).press('g');
  const physicsDownload=page.waitForEvent('download');
  await page.locator('#editable-download').click();
  const physicsPath=new URL(`${engine}-physics.hwpx`,evidence).pathname;
  await (await physicsDownload).saveAs(physicsPath);
  const physics=new HwpDocument(await readFile(physicsPath));
  const physicsText=Array.from({length:physics.getParagraphCount(0)},(_,n)=>physics.getTextRange(0,n,0,2000)).join('\n');
  assert.match(physicsText,/6\. 그림은 평면/);
  assert.match(physicsText,/g/);
  assert.equal(JSON.parse(physics.getControls()).filter(c=>c.ctrlId==='eqed').length,7);
  physics.free();
  const sourceWarnings=errors.filter(error=>/google-drive-gateway.*due to access control checks/u.test(error));
  assert.deepEqual(errors.filter(error=>!sourceWarnings.includes(error)),[]);
  observations.push({engine,sourceWarnings,firstCollectionClick:true,biologyHWPX:true,physicsNativeEquations:7,editedTextSaved:true,formatToggle:true,nestedZoom:true,responsiveRestore:true,detailMenu:true,landingTrackingLink:true,fileConversionEntry:true});
  await page.close();
 } finally {await browser.close();}
}
await writeFile(new URL('functional-results.json',evidence),JSON.stringify(observations,null,2));
console.log(JSON.stringify(observations,null,2));
